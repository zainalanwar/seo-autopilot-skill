#!/bin/bash
# SEO-Autopilot Setup Script
# Run this script to configure environment variables

echo "=========================================="
echo "SEO-Autopilot Setup"
echo "=========================================="
echo ""

# Check if .env exists
ENV_FILE=".env"

if [ -f "$ENV_FILE" ]; then
    echo "✓ .env file found"
    echo ""
    echo "Current configuration:"
    cat "$ENV_FILE" | grep -v "PASS\|KEY" | sed 's/=.*/=***/'
    echo ""
    read -p "Do you want to update? (y/n): " update
    if [ "$update" != "y" ]; then
        echo "Setup cancelled."
        exit 0
    fi
fi

echo ""
echo "Please provide the following information:"
echo ""

# MiMo API Key
echo "1. MiMo API Key"
echo "   Get from: https://platform.xiaomimimo.com"
read -p "   Enter MiMo API Key: " mimo_key
if [ -z "$mimo_key" ]; then
    echo "Error: MiMo API Key is required"
    exit 1
fi

# WordPress URL
echo ""
echo "2. WordPress URL"
read -p "   Enter WordPress URL (e.g., https://example.com): " wp_url
if [ -z "$wp_url" ]; then
    echo "Error: WordPress URL is required"
    exit 1
fi

# WordPress Username
echo ""
echo "3. WordPress Username"
read -p "   Enter WordPress Username: " wp_user
if [ -z "$wp_user" ]; then
    echo "Error: WordPress Username is required"
    exit 1
fi

# WordPress Password
echo ""
echo "4. WordPress Application Password"
echo "   Get from: WordPress Admin → Users → Your Profile → Application Passwords"
read -s -p "   Enter WordPress Application Password: " wp_pass
echo ""
if [ -z "$wp_pass" ]; then
    echo "Error: WordPress Application Password is required"
    exit 1
fi

# Create .env file
cat > "$ENV_FILE" << EOF
# SEO-Autopilot Environment Variables
# Generated by setup script on $(date)

# MiMo API Configuration
MIMO_API_KEY=$mimo_key
MIMO_BASE_URL=https://api.xiaomimimo.com/anthropic
MIMO_MODEL=mimo-v2.5-pro

# WordPress Configuration
WP_URL=$wp_url
WP_USER=$wp_user
WP_PASS=$wp_pass
EOF

# Set permissions
chmod 600 "$ENV_FILE"

echo ""
echo "=========================================="
echo "✓ Setup Complete!"
echo "=========================================="
echo ""
echo "Configuration saved to: $ENV_FILE"
echo ""
echo "Next steps:"
echo "  1. Test connection: ./seo test"
echo "  2. Run audit: ./seo audit https://your-site.com"
echo ""
